import type { Question } from '../../domain/question'

export interface TranslationTopicBank {
  topic: string
  questions: Question[]
}

interface TranslationEntry {
  chinese: string
  referenceAnswer: string
  explanation: string
  misconception: string
  difficulty: Question['difficulty']
}

function createTopicBank(
  topic: string,
  startNumber: number,
  checklist: string[],
  entries: TranslationEntry[],
): TranslationTopicBank {
  return {
    topic,
    questions: entries.map((entry, index) => ({
      id: `translation-${String(startNumber + index).padStart(3, '0')}`,
      type: 'translation',
      topic,
      difficulty: entry.difficulty,
      stem: `请将下列句子译成英语：${entry.chinese}`,
      options: [],
      answer: entry.referenceAnswer,
      referenceAnswer: entry.referenceAnswer,
      checklist,
      explanation: entry.explanation,
      misconception: entry.misconception,
      version: 1,
    })),
  }
}

